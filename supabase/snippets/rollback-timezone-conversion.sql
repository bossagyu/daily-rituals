-- ============================================================
-- reminder_time をローカル時刻から UTC へ戻す（コードロールバック用）
-- ============================================================
--
-- これはマイグレーション 20260813000000_add_user_timezone.sql が行った
-- 「reminder_time を UTC からユーザーのローカル時刻へ変換する」処理の逆変換。
--
-- 【使用条件】このアプリのコードを本コミット以前（reminder_time を UTC として
-- 扱っていた版）へロールバックする場合にのみ実行すること。コードが
-- ローカル時刻前提のまま動き続けるなら、このスクリプトを実行してはならない
-- （実行すると reminder_time が実際の意図から 9 時間前後ずれる）。
--
-- 【必ず一度だけ実行すること】このスクリプトはべき等ではない。二重実行すると
-- reminder_time がさらに UTC オフセット分（例: Asia/Tokyo なら 9 時間）ずれる。
-- 実行前に対象行の reminder_time をバックアップし、実行後は再実行しないこと。
--
-- 【profiles.timezone が順変換時から変わっていないことを確認すること】
-- 順変換（マイグレーション本体）は ALTER TABLE ... DEFAULT 'Asia/Tokyo' の直後に
-- 実行されたため、実質すべての行が 'Asia/Tokyo' として変換されている。しかし
-- その後アプリを起動すると useTimezoneSync がブラウザのタイムゾーンを
-- profiles.timezone へ書き込む。ユーザーが移動していた場合、この逆変換は
-- 順変換と異なるオフセットを使ってしまい、戻したはずの値がずれたまま残る。
-- 二重実行と違い、ずれても気づく手がかりがない。実行前に必ず確認すること:
--
--   SELECT DISTINCT timezone FROM profiles;
--
-- 'Asia/Tokyo' 以外が含まれる場合、そのユーザーの行は下の式では正しく戻らない。
-- 順変換時のタイムゾーン（= 'Asia/Tokyo'）を明示して個別に戻すこと。
--
-- 【profiles.timezone 列は残すこと】このロールバックは habits.reminder_time
-- のみを戻すもので、profiles.timezone 列自体をここで DROP してはならない。
-- 列を落とすと本ロールバック中に user_id ごとの変換係数を失い、後から
-- 変換のやり直しができなくなる。列を消すかどうかは別途判断する。
--
-- 【実行中はリマインダー設定を変更しないこと】このロールバック実行中および
-- ロールバック完了までの間、ユーザーがアプリの画面から reminder_time を
-- 編集すると、その編集がどちらの表現（ローカル/UTC）で保存されたか
-- 追跡できなくなり、当該行が中途半端な状態のまま残る。デプロイ切り替えと
-- このスクリプト実行を近接させ、その間はアプリを触らせないこと。
--
-- ⚠️ この式を他所へ流用しないこと。Postgres は名前付きタイムゾーンのオフセットを
-- 「アンカー日」基準で解決するため、DATE '2000-01-01' を使うこの書き方が正しいのは
-- 2000-01-01 時点と現在でオフセットが同じ地域（固定オフセットのタイムゾーン）に
-- 限られる。DST のある地域や 2000 年以降にオフセットを変えた地域では誤った時刻を
-- 生む。マイグレーション本体と同じ制約であり、そちらのコメントも参照。
--
-- 【マイグレーションディレクトリに置かないこと】このファイルは snippets/ 配下に
-- 置く。supabase/migrations/ に置くと `supabase db push` で自動適用され、
-- ロールバック不要な環境でも変換を巻き戻してしまう。手動で psql から実行する
-- 想定のスクリプトとして snippets/ に留める。
UPDATE habits h SET reminder_time =
  ((DATE '2000-01-01' + h.reminder_time) AT TIME ZONE p.timezone
     AT TIME ZONE 'UTC')::time
FROM profiles p
WHERE p.id = h.user_id AND h.reminder_time IS NOT NULL;
